async (page) => {
  const check = (ok, message) => { if (!ok) throw Error(message) }
  const errors = [], listRequests = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (r.url().includes('/assets?')) listRequests.push(new URL(r.url())) })
  const state = async () => (await page.request.get('http://127.0.0.1:3115/fixture/cover-state')).json()
  await page.request.post('http://127.0.0.1:3115/fixture/reset-cover-state')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:3115')
  await page.getByText('共 30 项', { exact: true }).waitFor()
  const before = await state()
  const first = before.assets.find(a => a.id === 'asset-0')
  await page.getByRole('button', { name: '取消封面素材 ORIGINAL.jpg', exact: true }).click()
  await page.getByRole('button', { name: '设为封面素材 ORIGINAL.jpg', exact: true }).waitFor()
  let latest = (await state()).assets.find(a => a.id === first.id)
  check(!latest.isCoverMaterial && latest.folderId === first.folderId && latest.materialClass === first.materialClass, 'Unmark changed source or folder')
  await page.getByRole('button', { name: '设为封面素材 ORIGINAL.jpg', exact: true }).click()
  await page.getByRole('button', { name: '取消封面素材 ORIGINAL.jpg', exact: true }).waitFor()
  await page.getByRole('button', { name: '素材目录', exact: true }).click()
  const nav = page.getByRole('dialog', { name: '选择素材目录' })
  await nav.getByRole('button', { name: '封面素材用途' }).click()
  await page.getByRole('tooltip').getByText('集中管理发布封面图片，可在新建草稿和排期时选择；原目录与来源类别保留。').waitFor()
  await nav.getByRole('button', { name: '封面素材', exact: true }).click()
  await page.getByText('共 25 项', { exact: true }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('[data-asset-id]').length === 24)
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('[data-asset-id]').length === 1)
  await page.getByRole('button', { name: '上一页', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('[data-asset-id]').length === 24)
  const ids = await page.locator('[data-asset-id]').evaluateAll(nodes => nodes.slice(0, 2).map(n => n.dataset.assetId))
  await page.locator('[data-asset-id]').nth(0).getByTitle('点击选择', { exact: true }).click()
  await page.locator('[data-asset-id]').nth(1).getByTitle('点击选择', { exact: true }).click()
  await page.getByRole('button', { name: '取消封面素材', exact: true }).click()
  await page.getByText('共 23 项', { exact: true }).waitFor()
  check((await state()).assets.filter(a => ids.includes(a.id)).every(a => !a.isCoverMaterial), 'Bulk unmark failed')
  await page.getByRole('button', { name: '上传素材', exact: true }).click()
  const upload = page.getByRole('dialog', { name: '上传素材', exact: true })
  check(await upload.getByRole('combobox', { name: '封面来源类别' }).inputValue() === 'UNCONFIRMED', 'Cover uploads must default to unconfirmed')
  check(await page.locator('input[type=file]').first().getAttribute('accept') === 'image/jpeg,image/png', 'Cover upload accepts unsupported media')
  await upload.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '管理文件夹', exact: true }).click()
  const manager = page.getByRole('dialog', { name: '管理文件夹', exact: true })
  const view = manager.locator('section').filter({ has: page.getByRole('heading', { name: '封面素材', exact: true }) })
  await view.waitFor()
  check(await view.getByRole('button', { name: /改名|移动|删除|新建/ }).count() === 0, 'Cover purpose view must be fixed')
  await manager.getByRole('button', { name: '关闭', exact: true }).click()
  await page.screenshot({ path: 'output/playwright/material-folders/covers-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '素材目录', exact: true }).click()
  await nav.getByRole('button', { name: '封面素材用途' }).click()
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile cover navigation overflows')
  await page.screenshot({ path: 'output/playwright/material-folders/covers-mobile.png', fullPage: true })

  // The actual publishing drawer uses the same purpose query, with all images
  // as an explicit fallback; selecting then cancelling never writes a purpose.
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:3115/?draft=1')
  await page.getByRole('button', { name: '新建发布草稿', exact: true }).click()
  const coverButton = page.getByRole('button', { name: '封面素材', exact: true })
  await coverButton.waitFor()
  check(listRequests.some(u => u.searchParams.get('coverOnly') === 'true' && u.searchParams.get('mediaType') === 'cover'), 'Draft cover picker does not use the shared purpose query')
  await page.getByRole('button', { name: '全部图片', exact: true }).click()
  const gallery = coverButton.locator('..').locator('..').locator('..')
  await gallery.getByTitle('ORIGINAL.jpg', { exact: true }).waitFor()
  const draftsBefore = (await state()).drafts.length
  await gallery.getByTitle('ORIGINAL.jpg', { exact: true }).click()
  await page.getByText('已选为草稿封面', { exact: true }).waitFor()
  check((await state()).drafts.length === draftsBefore, 'Selecting a cover unexpectedly saved the draft')
  // The drawer keeps the existing close action; no purpose writes happen until save.
  check(!(await state()).assets.find(a=>a.id==='asset-0').isCoverMaterial, 'Selecting an unmarked image wrote a purpose')
  await page.getByRole('button', { name: '关闭发布草稿' }).click()
  check((await state()).drafts.length === draftsBefore, 'Cancelling wrote a draft')
  await page.getByRole('button', { name: '新建发布草稿', exact: true }).click()
  await page.getByRole('button', { name: '全部图片', exact: true }).click()
  await gallery.getByTitle('ORIGINAL.jpg', { exact: true }).click()
  await page.getByRole('textbox', { name: /描述今日主题/ }).fill('封面关联测试')
  await page.getByText('已选为草稿封面', {exact:true}).waitFor()
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('heading', { name: '新建发布草稿', exact: true }).waitFor({state:'hidden'})
  const savedState=await state()
  check(savedState.drafts.length>draftsBefore&&savedState.drafts.every(d=>d.coverAssetId==='asset-0'),'Saved draft lost cover reference')
  check(savedState.assets.find(a=>a.id==='asset-0').isCoverMaterial,'Successful save did not mark cover')
  await page.request.post('http://127.0.0.1:3115/fixture/clear-covers')
  await page.getByRole('button', { name: '新建发布草稿', exact: true }).click()
  await page.getByText('尚未设置封面素材', {exact:true}).waitFor()
  check((await page.getByRole('link', {name:'前往封面素材'}).getAttribute('href')).includes('assetView=covers'),'Missing cover entry link')
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'从全部图片选择',exact:true}).click()
  await gallery.getByTitle('ORIGINAL.jpg',{exact:true}).waitFor()
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile draft cover picker overflows')
  await page.screenshot({path:'output/playwright/material-folders/draft-covers-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'关闭发布草稿'}).click()
  check(errors.length === 0, errors.join('; '))
  check(listRequests.every(u => u.searchParams.get('materialClass') !== 'COVERS' && u.searchParams.get('root') !== 'COVERS'), 'Purpose was treated as a material class')
  return { pass: true, coverage: 'fixed cover view; source/folder retention; shared counts; pagination; bulk mark; upload default; drawer query and all images; mobile' }
}
