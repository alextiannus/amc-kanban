async (page) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:3115')
  await page.getByRole('button', { name: '管理文件夹', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '管理文件夹', exact: true })
  await dialog.getByRole('heading', { name: '标准目录｜原始素材' }).waitFor()
  await dialog.getByRole('heading', { name: '自定义目录｜加工素材' }).waitFor()
  await dialog.getByRole('button', { name: '新建子目录', exact: true }).first().click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('新品实拍')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByText('新品实拍', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('combobox', { name: '素材目录', exact: true }).selectOption('food')
  await page.getByRole('button', { name: '管理文件夹', exact: true }).click()
  await dialog.getByRole('button', { name: '改名', exact: true }).first().click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('菜品原始素材')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByText('菜品原始素材', { exact: true }).waitFor()
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  if (await page.getByRole('combobox', { name: '素材目录', exact: true }).inputValue() !== 'food') throw Error('Rename lost selected folder identity')
  await page.getByRole('button', { name: '新建文件夹', exact: true }).click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('人工剪辑')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByRole('alert').waitFor()
  if (await dialog.getByRole('textbox', { name: '目录名称', exact: true }).inputValue() !== '人工剪辑') throw Error('Failed create lost input')
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('活动成片')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByText('活动成片', { exact: true }).waitFor()
  const row = name => dialog.locator('li').filter({ has: page.getByText(name, { exact: true }) }).last()
  await row('活动成片').getByRole('button', { name: '移动', exact: true }).click()
  await dialog.getByRole('combobox', { name: '父目录', exact: true }).selectOption('manual')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByRole('textbox', { name: '搜索目录', exact: true }).fill('活动成片')
  await row('活动成片').getByRole('button', { name: '删除', exact: true }).click()
  await dialog.getByRole('heading', { name: '删除空目录', exact: true }).waitFor()
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await row('活动成片').waitFor({ state: 'hidden' })
  await dialog.getByRole('textbox', { name: '搜索目录', exact: true }).fill('')
  await row('菜品原始素材').getByRole('button', { name: '改名', exact: true }).first().click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('冲突测试')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByRole('button', { name: '保留输入并使用最新版本', exact: true }).waitFor()
  if (await dialog.getByRole('textbox', { name: '目录名称', exact: true }).inputValue() !== '冲突测试') throw Error('Conflict lost input')
  await dialog.getByRole('button', { name: '保留输入并使用最新版本', exact: true }).click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('菜品原始素材')
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).waitFor({ state: 'hidden' })
  await page.screenshot({ path: 'output/playwright/material-folders/desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await dialog.getByRole('button', { name: '新建目录', exact: true }).click()
  await dialog.getByRole('textbox', { name: '目录名称', exact: true }).fill('手机运营素材')
  const bounds = await dialog.boundingBox()
  if (bounds.x < 0 || bounds.width > 391 || bounds.height > 845 || bounds.y < 0) throw Error('Mobile dialog is outside viewport')
  await page.screenshot({ path: 'output/playwright/material-folders/mobile.png' })
  await dialog.getByRole('button', { name: '确认', exact: true }).click()
  await dialog.getByRole('textbox', { name: '搜索目录', exact: true }).fill('手机运营素材')
  await dialog.getByText('手机运营素材', { exact: true }).waitFor()
  if (errors.length) throw Error(errors.join('\n'))
  console.log('PASS desktop/mobile folder tree, create, rename with selection preserved, move, empty delete, search, duplicate/conflict input retention and shared plus entry')
}
