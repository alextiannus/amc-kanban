async (page) => {
  const check = (ok, message) => { if (!ok) throw Error(message) }
  const writes = [], errors = []
  page.on('request', r => { if (['POST','PATCH','PUT','DELETE'].includes(r.method())) writes.push(r.url()) })
  page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:3115')
  await page.getByRole('button', { name: '待整理', exact: true }).click()
  const review = page.getByRole('dialog', { name: '待整理工作台' })
  const image = review.locator('li').filter({ has: page.getByRole('checkbox', { name: '选择 UNCONFIRMED.jpg', exact: true }) })
  await image.locator('img').waitFor()
  check(await image.locator('img').evaluate(n => n.complete && n.naturalWidth > 0), 'Image thumbnail did not render')
  await image.getByRole('checkbox').check()
  await image.getByRole('button', { name: '预览 UNCONFIRMED.jpg' }).click()
  const viewer = review.getByRole('region', { name: '素材预览' })
  await viewer.getByRole('img', { name: 'UNCONFIRMED.jpg' }).waitFor()
  await viewer.getByRole('button', { name: '返回整理列表' }).click()
  check(await image.getByRole('checkbox').isChecked(), 'Preview changed selection')
  const covered = review.locator('li').filter({ has: page.getByRole('checkbox', { name: '选择 有封面视频.mp4', exact: true }) })
  check(await covered.locator('img').count() === 1 && await covered.locator('video').count() === 0, 'Existing cover should use a static image')
  await covered.getByRole('button', { name: '预览 有封面视频.mp4' }).click()
  const video = viewer.locator('video')
  await video.waitFor()
  await video.evaluate(n => { window.reviewPlayer = n; return n.play() })
  await page.waitForFunction(() => window.reviewPlayer.currentTime > 0)
  check(await video.getAttribute('controls') !== null, 'Video player needs controls')
  await viewer.getByRole('button', { name: '返回整理列表' }).click()
  check(await page.evaluate(() => window.reviewPlayer.paused && !window.reviewPlayer.hasAttribute('src')), 'Returning did not release the player')
  const frameless = review.locator('li').filter({ has: page.getByRole('checkbox', { name: '选择 无封面视频.mp4', exact: true }) })
  await frameless.locator('video').waitFor()
  await page.waitForFunction(() => [...document.querySelectorAll('[data-review-id="review-video-frame"] video')].some(n => n.readyState >= 2))
  const broken = review.locator('li').filter({ has: page.getByRole('checkbox', { name: '选择 失效图片.jpg', exact: true }) })
  await broken.getByText('封面不可用，点击预览').waitFor()
  await broken.getByRole('button', { name: '预览 失效图片.jpg' }).click()
  await viewer.getByText('预览加载失败，请尝试打开原文件。').waitFor()
  await viewer.getByRole('link', { name: '打开原文件' }).waitFor()
  await page.keyboard.press('Escape')
  check(await review.isVisible(), 'Escape from preview should return to list')
  await review.getByRole('button', { name: '预览整理', exact: true }).click()
  await review.getByRole('heading', { name: '确认整理 1 项' }).waitFor()
  await review.getByRole('button', { name: '预览 UNCONFIRMED.jpg' }).click()
  await viewer.getByRole('img').waitFor()
  await viewer.getByRole('button', { name: '返回整理列表' }).click()
  await review.getByRole('heading', { name: '确认整理 1 项' }).waitFor()
  await review.getByRole('button', { name: '返回修改', exact: true }).click()
  await page.screenshot({ path: 'output/playwright/material-folders/cleanup-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await covered.getByRole('button', { name: '预览 有封面视频.mp4' }).scrollIntoViewIfNeeded()
  const position = await review.evaluate(n => n.scrollTop)
  await covered.getByRole('button', { name: '预览 有封面视频.mp4' }).click()
  await viewer.locator('video').waitFor()
  check(await review.evaluate(n => n.scrollWidth <= n.clientWidth + 1), 'Mobile preview overflows')
  await viewer.getByRole('button', { name: '返回整理列表' }).click()
  check(Math.abs(await review.evaluate(n => n.scrollTop) - position) < 2, 'Preview return lost scroll position')
  check(await image.getByRole('checkbox').isChecked(), 'Mobile preview changed selection')
  check(await review.evaluate(n => n.scrollWidth <= n.clientWidth + 1), 'Mobile review list overflows')
  await page.screenshot({ path: 'output/playwright/material-folders/cleanup-mobile.png', fullPage: true })
  await review.getByRole('button', { name: '关闭', exact: true }).click()
  check(writes.length === 0, 'Media previews must not write filing or classification')
  check(errors.length === 0, errors.join('; '))
  return { pass: true, coverage: 'images; static video cover; first frame; playback; release; broken media; selection; confirmation; Escape; mobile; no writes' }
}
